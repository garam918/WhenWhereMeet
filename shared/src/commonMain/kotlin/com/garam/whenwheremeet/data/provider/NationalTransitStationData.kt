    private fun parseStation(row: String): TransitStation {
        val columns = row.split('|', limit = 6)
        require(columns.size == 6) { "Invalid transit station row" }
        return TransitStation(
            id = columns[0],
            name = columns[1],
            latitude = columns[2].toDouble(),
            longitude = columns[3].toDouble(),
            region = columns[4],
            lines = columns[5].split(',').filter(String::isNotBlank),
        )
    }
